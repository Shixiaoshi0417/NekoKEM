/**
 * The Material 3 Expressive style's main colors. Each scheme is the Material
 * color utilities' fidelity scheme for the seed: the primary color stays close
 * to the seed, and the surfaces stay near neutral. Blue is the default.
 */
enum class ThemeColor(val tag: String, @StringRes val labelResource: Int, val seed: Color) {
    BLUE("blue", R.string.theme_color_blue, Color(0xFF1A73E8)),
    PURPLE("purple", R.string.theme_color_purple, Color(0xFF6750A4)),
    GREEN("green", R.string.theme_color_green, Color(0xFF2E7D32)),
    TEAL("teal", R.string.theme_color_teal, Color(0xFF00796B)),
    ORANGE("orange", R.string.theme_color_orange, Color(0xFFE8710A)),
    RED("red", R.string.theme_color_red, Color(0xFFD93025)),
    ;

    fun scheme(dark: Boolean): ColorScheme = when (this) {
        BLUE -> if (dark) BlueDark else BlueLight
        PURPLE -> if (dark) PurpleDark else PurpleLight
        GREEN -> if (dark) GreenDark else GreenLight
        TEAL -> if (dark) TealDark else TealLight
        ORANGE -> if (dark) OrangeDark else OrangeLight
        RED -> if (dark) RedDark else RedLight
    }
}

/** The Material style's color choice, kept in this device's private preferences. */
data class ThemeColorSettings(val color: ThemeColor = ThemeColor.BLUE, val dynamic: Boolean = false)

object ThemeColors {
    private const val PREFERENCES = "interface_style"
    private const val COLOR = "theme_color"
    private const val DYNAMIC = "dynamic_color"

    /** Wallpaper colors need Android 12. */
    val dynamicSupported: Boolean get() = Build.VERSION.SDK_INT >= Build.VERSION_CODES.S

    fun selection(context: Context): ThemeColorSettings {
        val preferences = context.getSharedPreferences(PREFERENCES, Context.MODE_PRIVATE)
        val tag = try { preferences.getString(COLOR, null) } catch (_: ClassCastException) { null }
        val dynamic = try { preferences.getBoolean(DYNAMIC, false) } catch (_: ClassCastException) { false }
        return ThemeColorSettings(ThemeColor.entries.firstOrNull { it.tag == tag } ?: ThemeColor.BLUE, dynamic)
    }

    /** Returns false when the choice could not be written; the previous one then stays. */
    fun setSelection(context: Context, settings: ThemeColorSettings): Boolean =
        context.getSharedPreferences(PREFERENCES, Context.MODE_PRIVATE).edit()
            .putString(COLOR, settings.color.tag)
            .putBoolean(DYNAMIC, settings.dynamic)
            .commit()
}

